#!/usr/bin/env python3
"""Generate tests.yml (promtool unit tests) for postfiat.rules.yml.

Input series and evaluation times below are written by hand: one firing case
and one non-firing case per alert. Only exp_annotations are copied from the
rules file (with {{ $labels.instance }} rendered) so a wording change in an
annotation does not require editing every test by hand.

Usage: python3 gen_tests.py > tests.yml && promtool test rules tests.yml
"""
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
L = 'job="postfiat", instance="node:9877"'
LBL = {"job": "postfiat", "instance": "node:9877"}

# alert -> (interval, firing_series, firing_eval, quiet_series, quiet_eval)
CASES = {
    "PFTExporterDown": ("1m", {"up": "0x5"}, "3m", {"up": "0 0 0 1 1 1"}, "3m"),
    "PFTNodeRPCDown": ("1m", {"pft_up": "0x3"}, "2m", {"pft_up": "1x3"}, "2m"),
    "PFTNodeNotFull": ("1m", {'pft_server_state{state="syncing"}': "2x10"}, "6m",
                       {'pft_server_state{state="full"}': "4x10"}, "6m"),
    "PFTValidatorNotProposing": ("1m", {'pft_server_state{state="full"}': "4x15", "pft_validator_configured": "1x15"},
                                 "11m",
                                 {'pft_server_state{state="full"}': "4x15", "pft_validator_configured": "0x15"},
                                 "11m"),
    "PFTNoPeers": ("1m", {"pft_peers": "0x5"}, "3m", {"pft_peers": "10x5"}, "3m"),
    "PFTLowPeers": ("1m", {"pft_peers": "3x12"}, "11m", {"pft_peers": "0x12"}, "11m"),
    "PFTValidatedLedgerOld": ("1m", {"pft_validated_ledger_age_seconds": "120x5"}, "3m",
                              {"pft_validated_ledger_age_seconds": "2x5"}, "3m"),
    "PFTValidatedLedgerStalled": ("1m", {"pft_validated_ledger_seq": "100x10", "pft_up": "1x10"}, "7m",
                                  {"pft_validated_ledger_seq": "100+12x10", "pft_up": "1x10"}, "7m"),
    "PFTCompleteLedgersGap": ("1m", {"pft_complete_ledgers_ranges": "2x40"}, "31m",
                              {"pft_complete_ledgers_ranges": "1x40"}, "31m"),
    "PFTCloseTimeDrift": ("1m", {"pft_close_time_offset_seconds": "-10x12"}, "11m",
                          {"pft_close_time_offset_seconds": "2x12"}, "11m"),
    "PFTHighLoadFactor": ("1m", {"pft_load_factor": "256x12"}, "11m", {"pft_load_factor": "1x12"}, "11m"),
    "PFTContainerRestarted": ("1m", {"pft_uptime_seconds": "1000+60x5 30+60x5"}, "8m",
                              {"pft_uptime_seconds": "1000+60x11"}, "8m"),
    "PFTContainerRestartLoop": ("1m", {"pft_uptime_seconds": "0+60x5 0+60x5 0+60x5 0+60x5"}, "22m",
                                {"pft_uptime_seconds": "0+60x5 0+60x5 0+60x5"}, "17m"),
    "PFTDiskSpaceLow": ("1m", {"pft_disk_avail_bytes": "10x12", "pft_disk_size_bytes": "100x12"}, "11m",
                        {"pft_disk_avail_bytes": "50x12", "pft_disk_size_bytes": "100x12"}, "11m"),
    "PFTDiskSpaceCritical": ("1m", {"pft_disk_avail_bytes": "3x8", "pft_disk_size_bytes": "100x8"}, "6m",
                             {"pft_disk_avail_bytes": "10x8", "pft_disk_size_bytes": "100x8"}, "6m"),
    "PFTDiskWillFillIn24h": ("1m", {"pft_disk_avail_bytes": "29-0.05x150", "pft_disk_size_bytes": "100x150"}, "2h",
                             {"pft_disk_avail_bytes": "29x150", "pft_disk_size_bytes": "100x150"}, "2h"),
}


def series(spec):
    out = []
    for name, values in spec.items():
        if "{" in name:
            metric = name[:-1] + ", " + L + "}"
        else:
            metric = name + "{" + L + "}"
        out.append({"series": metric, "values": values})
    return out


def main():
    with open(os.path.join(HERE, "postfiat.rules.yml")) as f:
        rules = {r["alert"]: r for g in yaml.safe_load(f)["groups"] for r in g["rules"]}
    missing = set(rules) - set(CASES)
    if missing:
        sys.exit("no test case for: %s" % ", ".join(sorted(missing)))
    tests = []
    for alert, (interval, fire, fire_at, quiet, quiet_at) in CASES.items():
        r = rules[alert]
        ann = {k: v.replace("{{ $labels.instance }}", LBL["instance"]) for k, v in r["annotations"].items()}
        exp = [{"exp_labels": dict(LBL, severity=r["labels"]["severity"]), "exp_annotations": ann}]
        tests.append({"name": alert + " fires", "interval": interval, "input_series": series(fire),
                      "alert_rule_test": [{"eval_time": fire_at, "alertname": alert, "exp_alerts": exp}]})
        tests.append({"name": alert + " stays quiet", "interval": interval, "input_series": series(quiet),
                      "alert_rule_test": [{"eval_time": quiet_at, "alertname": alert, "exp_alerts": []}]})
    print("# GENERATED by gen_tests.py - one firing and one non-firing case per alert.")
    print("# Run: promtool test rules tests.yml")
    print(yaml.safe_dump({"rule_files": ["postfiat.rules.yml"], "evaluation_interval": "1m", "tests": tests},
                         sort_keys=False, width=120), end="")


if __name__ == "__main__":
    main()
